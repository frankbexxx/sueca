import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(__dirname, '../src/generated/buildInfo.ts');

let version = 'dev';
try {
  const vercelSha = process.env.VERCEL_GIT_COMMIT_SHA;
  if (vercelSha) {
    version = vercelSha.slice(0, 7);
  } else {
    version = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
  }
} catch {
  /* not a git checkout */
}

const content = `/** Generated by scripts/write-build-info.mjs — do not edit manually */
export const BUILD_VERSION = ${JSON.stringify(version)};
export const BUILD_TIME = ${JSON.stringify(new Date().toISOString())};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content);
console.log(`buildInfo: ${version}`);
