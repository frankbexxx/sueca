import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.join(__dirname, '..');
const repoRoot = path.join(frontendRoot, '..');
const outPath = path.join(frontendRoot, 'src/generated/buildInfo.ts');

function shortSha(value) {
  if (!value || typeof value !== 'string') return null;
  const trimmed = value.trim();
  if (/^[0-9a-f]{7,40}$/i.test(trimmed)) {
    return trimmed.slice(0, 7);
  }
  return null;
}

function gitShortHead(cwd) {
  try {
    return execSync('git rev-parse --short HEAD', { encoding: 'utf8', cwd }).trim();
  } catch {
    return null;
  }
}

function readExistingVersion() {
  try {
    const existing = fs.readFileSync(outPath, 'utf8');
    const match = existing.match(/BUILD_VERSION = "([^"]+)"/);
    if (match && match[1] !== 'dev') {
      return match[1];
    }
  } catch {
    /* first build */
  }
  return null;
}

function resolveVersion() {
  const explicit = shortSha(process.env.BUILD_VERSION);
  if (explicit) return { version: explicit, source: 'BUILD_VERSION' };

  const ciSha = shortSha(process.env.VERCEL_GIT_COMMIT_SHA)
    || shortSha(process.env.GITHUB_SHA)
    || shortSha(process.env.CI_COMMIT_SHA);
  if (ciSha) return { version: ciSha, source: 'CI env' };

  const fromGit =
    gitShortHead(repoRoot) || gitShortHead(frontendRoot) || gitShortHead(process.cwd());
  if (fromGit) return { version: fromGit, source: 'git' };

  const existing = readExistingVersion();
  if (existing) return { version: existing, source: 'existing buildInfo.ts' };

  return { version: 'dev', source: 'fallback' };
}

const { version, source } = resolveVersion();

const content = `/** Generated by scripts/write-build-info.mjs — do not edit manually */
export const BUILD_VERSION = ${JSON.stringify(version)};
export const BUILD_TIME = ${JSON.stringify(new Date().toISOString())};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content);
console.log(`buildInfo: ${version} (${source})`);
