import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.join(__dirname, '..');
const repoRoot = path.join(frontendRoot, '..');
const outPath = path.join(frontendRoot, 'src/generated/buildInfo.ts');
const packageJsonPath = path.join(frontendRoot, 'package.json');

function shortSha(value) {
  if (!value || typeof value !== 'string') return null;
  const trimmed = value.trim();
  if (/^[0-9a-f]{7,40}$/i.test(trimmed)) {
    return trimmed.slice(0, 7);
  }
  return null;
}

function gitShortHead(cwd) {
  try {
    return execSync('git rev-parse --short HEAD', { encoding: 'utf8', cwd }).trim();
  } catch {
    return null;
  }
}

/** True when the git worktree has uncommitted changes. False on failure / no git. */
function gitWorktreeDirty(cwd) {
  try {
    const out = execSync('git status --porcelain', {
      encoding: 'utf8',
      cwd,
      stdio: ['ignore', 'pipe', 'ignore']
    });
    return out.trim().length > 0;
  } catch {
    return false;
  }
}

function readExistingBuildVersion() {
  try {
    const existing = fs.readFileSync(outPath, 'utf8');
    const match = existing.match(/BUILD_VERSION = "([^"]+)"/);
    if (match && match[1] !== 'dev') {
      return match[1];
    }
  } catch {
    /* first build */
  }
  return null;
}

function withDirtySuffix(version, dirty) {
  if (!dirty) return version;
  if (version.endsWith('-dirty')) return version;
  return `${version}-dirty`;
}

function resolveBuildVersion() {
  const explicit = shortSha(process.env.BUILD_VERSION);
  if (explicit) {
    // Explicit CI/release SHA stays clean unless FORCE_DIRTY_BUILD=1.
    const dirty = process.env.FORCE_DIRTY_BUILD === '1';
    return { version: withDirtySuffix(explicit, dirty), source: 'BUILD_VERSION', dirty };
  }

  const ciSha =
    shortSha(process.env.VERCEL_GIT_COMMIT_SHA) ||
    shortSha(process.env.GITHUB_SHA) ||
    shortSha(process.env.CI_COMMIT_SHA);
  if (ciSha) {
    return { version: ciSha, source: 'CI env', dirty: false };
  }

  const fromGit =
    gitShortHead(repoRoot) || gitShortHead(frontendRoot) || gitShortHead(process.cwd());
  if (fromGit) {
    const dirty =
      gitWorktreeDirty(repoRoot) ||
      gitWorktreeDirty(frontendRoot) ||
      gitWorktreeDirty(process.cwd());
    return { version: withDirtySuffix(fromGit, dirty), source: 'git', dirty };
  }

  const existing = readExistingBuildVersion();
  if (existing) return { version: existing, source: 'existing buildInfo.ts', dirty: false };

  return { version: 'dev', source: 'fallback', dirty: false };
}

function resolveAppVersion() {
  try {
    const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
    if (typeof pkg.version === 'string' && pkg.version.trim()) {
      return pkg.version.trim();
    }
  } catch {
    /* fall through */
  }
  return '0.0.0';
}

const { version: buildVersion, source, dirty } = resolveBuildVersion();
const appVersion = resolveAppVersion();

const content = `/** Generated by scripts/write-build-info.mjs — do not edit manually */
export const APP_VERSION = ${JSON.stringify(appVersion)};
export const BUILD_VERSION = ${JSON.stringify(buildVersion)};
export const BUILD_DIRTY = ${dirty ? 'true' : 'false'};
export const BUILD_TIME = ${JSON.stringify(new Date().toISOString())};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content);
console.log(`buildInfo: app=${appVersion} build=${buildVersion} (${source}${dirty ? ', dirty' : ''})`);
